"""Write skills/coordinate-reference/datums.md from the EPSG dataset, so the skill's reference table is generated, not
typed. Reads PROJ's copy of EPSG (proj.db, shipped with pyproj): pip install pyproj, then
python3 scripts/build-datums.py. Rerun after upgrading pyproj to pick up a new EPSG release, and check anything that
matters against the live registry (epsg.org)."""
import os, sqlite3, pyproj

DB = sqlite3.connect(os.path.join(pyproj.datadir.get_data_dir(), "proj.db"))
META = dict(DB.execute("select key, value from metadata"))

# Datums most often met in energy and land work, with why they matter. Code = the geographic 2D CRS.
DATUMS = [
    ("4277", "Great Britain", "British National Grid (EPSG:27700) and older UK maps and records."),
    ("4230", "Europe, North Sea", "Older North Sea well, licence and installation positions; ED50 / UTM zones 29–32 (EPSG:23029–23032)."),
    ("4258", "Europe", "Today's European mapping (ETRS89 / UTM, national grids); moves with the plate, so it drifts from WGS 84 by about 2.5 cm a year."),
    ("4300", "Ireland", "Irish Grid (EPSG:29903)."),
    ("4267", "North America", "Older US and Canadian records; State Plane and UTM on NAD27."),
    ("4269", "North America", "Today's US and Canadian mapping before NATRF2022; within about 1–2 m of WGS 84."),
    ("4263", "Nigeria", "Nigerian oil and gas concessions (OMLs, OPLs); Nigeria East/Mid/West Belt grids."),
    ("4220", "Angola", "Angolan offshore blocks."),
    ("4210", "Kenya, Tanzania", "East African mapping."),
    ("4298", "Brunei, Sabah, Sarawak", "Borneo oil and gas; RSO Borneo grids."),
    ("4245", "Malaysia (west), Singapore", "Peninsular Malaysia."),
    ("4248", "South America (Andes)", "PSAD56: Peru, Ecuador, Venezuela, Bolivia, Chile."),
    ("4618", "South America", "SAD69: Brazil and neighbours."),
    ("4283", "Australia", "GDA94; superseded by GDA2020 (EPSG:7844), 1.8 m apart because of plate motion."),
    ("4167", "New Zealand", "NZGD2000."),
]

TABLES = ["helmert_transformation", "grid_transformation", "other_transformation", "concatenated_operation"]


def name(code):
    for t in ("geodetic_crs", "projected_crs"):
        r = DB.execute(f"select name from {t} where auth_name='EPSG' and code=?", (code,)).fetchone()
        if r:
            return r[0]
    return "?"


def options(src):
    rows = []
    for t in TABLES:
        method = "c.method_name" if t != "concatenated_operation" else "'concatenated'"
        q = f"""select c.code, c.name, c.accuracy, e.name, {method if t != 'concatenated_operation' else "'concatenated'"}
                from {t} c join usage u on u.object_table_name='{t}' and u.object_auth_name=c.auth_name and u.object_code=c.code
                join extent e on e.auth_name=u.extent_auth_name and e.code=u.extent_code
                where c.auth_name='EPSG' and c.source_crs_auth_name='EPSG' and c.source_crs_code=? and c.target_crs_code='4326' and c.deprecated=0"""
        try:
            rows += [(*r, t) for r in DB.execute(q, (src,))]
        except sqlite3.OperationalError:
            q = q.replace("c.method_name", "''")
            rows += [(*r, t) for r in DB.execute(q, (src,))]
    seen, out = set(), []
    for r in sorted(rows, key=lambda r: (r[2] if r[2] is not None else 999, r[0])):
        if r[0] in seen:
            continue
        seen.add(r[0])
        out.append(r)
    return out


lines = [
    "# Datums and transformations to WGS 84 most often met",
    "",
    f"*Generated by `scripts/build-datums.py` from EPSG {META.get('EPSG.VERSION')} ({META.get('EPSG.DATE')}), as carried by "
    f"PROJ {META.get('PROJ.VERSION')}. Live records: epsg.org. Don't edit by hand: rerun the script.*",
    "",
    "For each datum: the live (not deprecated) transformations to WGS 84 (EPSG:4326), best stated accuracy first, up to "
    "eight. Choose by the site's position (the area of use must contain it), then accuracy; see SKILL.md, section 4. "
    "\"grid\" means the transformation needs a grid file; \"concatenated\" chains several operations. Accuracy is EPSG's "
    "stated figure in metres; blank means not stated.",
    "",
]
for code, region, why in DATUMS:
    opts = options(code)
    lines += [f"## {name(code)} (EPSG:{code}) — {region}", "", why, "",
              f"{len(opts)} live transformations to WGS 84." + (" The first eight:" if len(opts) > 8 else ""), "",
              "| EPSG | Name | Area of use | Accuracy (m) | Kind |", "|---|---|---|---|---|"]
    for c, n, acc, area, method, t in opts[:8]:
        kind = {"grid_transformation": "grid", "concatenated_operation": "concatenated"}.get(t, method or "")
        lines.append(f"| {c} | {n} | {area} | {'' if acc is None else (int(acc) if float(acc).is_integer() else acc)} | {kind} |")
    lines.append("")

# The WGS 84 ensemble itself.
ens = DB.execute("select ensemble_accuracy from geodetic_datum where auth_name='EPSG' and code='6326'").fetchone()
members = DB.execute("select count(*) from geodetic_datum_ensemble_member where ensemble_auth_name='EPSG' and ensemble_code='6326'").fetchone()
lines += ["## WGS 84 itself", "",
          f"WGS 84 (datum EPSG:6326) is an ensemble of {members[0]} realisations, accurate as a whole to about {ens[0]:g} m. "
          "Good enough for screening; record the realisation and epoch for survey-grade work.", ""]

out = os.path.join(os.path.dirname(__file__), "..", "skills", "coordinate-reference", "datums.md")
with open(out, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {out}: {len(DATUMS)} datums, EPSG {META.get('EPSG.VERSION')}")
