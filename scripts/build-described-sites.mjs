// Builds the "described location" test set for place finding (test data only; the product never uses it).
// For each verified IFC site, fetch its Environmental and Social Review Summary (CC BY 4.0), keep the sentences
// that say where the project is, and have Claude condense them into a short location description with any
// coordinates removed. Rob spot-checks the result before it's used for scoring.
// Usage: ANTHROPIC_API_KEY=... node scripts/build-described-sites.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const csv = readFileSync("data/eval_set.csv", "utf8").trim().split(/\r?\n/);
const head = csv[0].split(",");
const rows = csv.slice(1).map((l) => {
  const cells = l.match(/("([^"]|"")*"|[^,]*)(,|$)/g).map((c) => c.replace(/,$/, "").replace(/^"|"$/g, "").replace(/""/g, '"'));
  return Object.fromEntries(head.map((h, i) => [h, cells[i]]));
}).filter((r) => ["correct", "moved"].includes(r.location_status) && r.lat && r.lon && r.esrs_url);

const UA = { "User-Agent": "gis-analyst-eval/1.0 (+https://github.com/pushpingeo/gis-analyst)" };
const CUES = /\b(located|location|situated|km|kilomet|district|province|region|county|municipalit|village|town|city|near|adjacent|north|south|east|west|river|lake|coast|valley|plateau|border|road|highway)\b/i;
const COORDS = /(-?\d{1,3}\.\d{3,}\s*°?\s*[NSEW]?\s*,?\s*-?\d{1,3}\.\d{3,})|(\d{1,3}\s*°\s*\d{1,2}\s*['′])/;

const text = (html) => html.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/gi, " ").replace(/<[^>]+>/g, " ")
  .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&#39;|&rsquo;/g, "'").replace(/&quot;|&ldquo;|&rdquo;/g, '"').replace(/\s+/g, " ");

async function claude(prompt) {
  const r = await fetch("https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers: { "content-type": "application/json", "x-api-key": process.env.ANTHROPIC_API_KEY, "anthropic-version": "2023-06-01" },
    body: JSON.stringify({ model: "claude-haiku-5-5", max_tokens: 4000, messages: [{ role: "user", content: prompt }] }),
  });
  if (!r.ok) throw new Error(`API ${r.status}: ${(await r.text()).slice(0, 200)}`);
  const j = await r.json();
  return j.content.filter((b) => b.type === "text").map((b) => b.text).join("");
}

mkdirSync("eval/places/sets", { recursive: true });
// Keep descriptions already made; only redo sites that failed or are new.
let previous = [];
try { previous = JSON.parse(readFileSync("eval/places/sets/described-sites.json", "utf8")); } catch { /* first run */ }
const out = [];
for (const s of rows) {
  const done = previous.find((p) => p.project === s.project_number && p.description && !p.error);
  if (done) { out.push(done); continue; }
  let rec = { project: s.project_number, name: s.name, country: s.country, sector: s.sector, site_type: s.site_type, source: s.esrs_url, lat: +s.lat, lon: +s.lon };
  try {
    const r = await fetch(s.esrs_url, { headers: UA });
    if (!r.ok) throw new Error(`ESRS ${r.status}`);
    const sentences = text(await r.text()).split(/(?<=[.;])\s+(?=[A-Z])/).filter((x) => x.length > 30 && x.length < 600 && CUES.test(x));
    const loc = sentences.filter((x) => /\b(located|situated|location|km\b|kilomet)/i.test(x)).slice(0, 25);
    rec.sentences = loc;
    if (!loc.length) throw new Error("no location sentences found");
    const reply = await claude(`These sentences come from an IFC disclosure about a project in ${s.country} (${s.sector}; ${s.site_type}).

${loc.map((x, i) => `${i + 1}. ${x}`).join("\n")}

Write a short location description (one to three sentences) that a GIS analyst could use to find the main project site on a map: keep place names, districts, rivers, distances and directions; leave out any coordinates; leave out sentences about distant ports, suppliers or offices unless they help locate the site. Then list the clues.
Reply with JSON only: {"description": "...", "clues": ["..."], "had_coordinates": true|false, "enough_to_locate": true|false}`);
    if (!reply.includes("{")) throw new Error("the reply had no JSON");
    const j = JSON.parse(reply.slice(reply.indexOf("{"), reply.lastIndexOf("}") + 1));
    if (COORDS.test(j.description)) { j.description = j.description.replace(COORDS, "[coordinates removed]"); j.had_coordinates = true; }
    rec = { ...rec, ...j };
  } catch (e) {
    rec.error = e.message;
  }
  out.push(rec);
  console.log(`${s.name}: ${rec.error || rec.description}`);
  writeFileSync("eval/places/sets/described-sites.json", JSON.stringify(out, null, 1));
}

// A table for Rob to check: one row per site.
const md = ["# Described locations for the place-finding test (check before use)", "",
  "From each project's IFC Environmental and Social Review Summary (CC BY 4.0). Generated by `scripts/build-described-sites.mjs`; the verified locations are not shown to the model.", "",
  "| Project | Country | Description | Enough? | Source |", "|---|---|---|---|---|",
  ...out.map((r) => `| ${r.name} | ${r.country} | ${(r.description || `*${r.error}*`).replace(/\|/g, "/")} | ${r.enough_to_locate === false ? "no" : r.error ? "–" : "yes"} | [ESRS](${r.source}) |`)];
writeFileSync("eval/places/sets/described-sites.md", md.join("\n") + "\n");
